/**
 * Bundles the AudioWorklet processor into a JavaScript string.
 *
 * Consumers load the worklet from a Blob URL (see `audio/workletModuleUrl.ts`),
 * so the processor must reach them as text inside the library bundle rather
 * than as a separate file that every bundler would have to know about. This
 * script writes that text to `src/audio/sampleCaptureWorklet.source.ts`; the
 * file is committed and a test fails when it is out of date.
 *
 *   npm run build:worklet -w packages/core
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
export const WORKLET_ENTRY = path.resolve(here, "../src/audio/sampleCapture.worklet.ts");
export const WORKLET_SOURCE_FILE = path.resolve(
  here,
  "../src/audio/sampleCaptureWorklet.source.ts",
);

/** The processor and its imports as one self-contained script. */
export async function bundleWorklet(): Promise<string> {
  const result = await build({
    entryPoints: [WORKLET_ENTRY],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
  });
  return result.outputFiles[0].text.trim();
}

/** The TypeScript module that embeds `source`. */
export function renderWorkletModule(source: string): string {
  return [
    "// Generated by scripts/buildWorklet.ts from sampleCapture.worklet.ts. Do not edit.",
    "/** The sample-capture AudioWorkletProcessor, bundled as a script. */",
    `export const SAMPLE_CAPTURE_WORKLET_SOURCE = ${JSON.stringify(source)};`,
    "",
  ].join("\n");
}

const invokedDirectly =
  process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  const source = await bundleWorklet();
  await writeFile(WORKLET_SOURCE_FILE, renderWorkletModule(source));
  console.log(
    `wrote ${path.relative(process.cwd(), WORKLET_SOURCE_FILE)} (${source.length} bytes)`,
  );
}
